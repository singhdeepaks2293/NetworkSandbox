//! MD5 (RFC 1321) and HMAC-MD5 (RFC 2104).
//!
//! IEEE 802.1Q-2005 clause 13.7 defines the MST Configuration Digest as an
//! HMAC-MD5 signature over the 4096-entry VID to MSTID table, keyed with the
//! fixed 16-octet string from Table 13-1.  The standard library has no digest
//! support and this project intentionally keeps its dependency set to `libc`,
//! so the two small algorithms live here.
//!
//! The implementation is deliberately straightforward (no tables beyond the
//! standard MD5 shift amounts) and is covered by RFC test vectors.

const S: [u32; 64] = [
    7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22, 5, 9, 14, 20, 5, 9, 14, 20, 5, 9,
    14, 20, 5, 9, 14, 20, 4, 11, 16, 23, 4, 11, 16, 23, 4, 11, 16, 23, 4, 11, 16, 23, 6, 10, 15,
    21, 6, 10, 15, 21, 6, 10, 15, 21, 6, 10, 15, 21,
];

